package org.alfresco.indexing.security;

import org.springframework.boot.context.properties.EnableConfigurationProperties;
import org.springframework.boot.web.servlet.FilterRegistrationBean;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.Ordered;

/**
 * Registers the {@link SharedSecretFilter} in front of the whole HTTP surface.
 */
@Configuration
@EnableConfigurationProperties(ServerSecurityProperties.class)
public class SecurityConfiguration
{
    @Bean
    public FilterRegistrationBean<SharedSecretFilter> sharedSecretFilterRegistration(
        ServerSecurityProperties properties)
    {
        FilterRegistrationBean<SharedSecretFilter> registration =
            new FilterRegistrationBean<>(new SharedSecretFilter(properties));
        registration.addUrlPatterns("/*");
        registration.setOrder(Ordered.HIGHEST_PRECEDENCE);
        return registration;
    }
}
